_DEG_M = 111_320.0


def _dist_m(a: tuple[float, float], b: tuple[float, float]) -> float:
    """两点间大圆距离的等距圆柱近似（区域 <5km，误差可忽略）。"""
    dn = (a[0] - b[0]) * _DEG_M
    de = (a[1] - b[1]) * _DEG_M * math.cos(math.radians((a[0] + b[0]) / 2))
    return math.hypot(dn, de)


def match_route(lat: float, lon: float, tol_m: float = 100.0) -> int | None:
    """按路线 Start 匹配路线索引，容差外返回 None（验证集新路线）。"""
    best_i, best_d = None, tol_m
    for i, route in enumerate(ROUTES):
        d = _dist_m((lat, lon), (route[0][0], route[0][1]))
        if d < best_d:
            best_i, best_d = i, d
    return best_i


def predict_position(route_idx: int, elapsed_s: float,
                     speed_mps: float) -> tuple[float, float]:
    """沿路线推移 elapsed_s 后的位置（节点处先停 WaitTime 再驶向下点），
    越过 End 后停在 End。"""
    route = ROUTES[route_idx]
    t = max(0.0, elapsed_s)
    for i in range(len(route) - 1):
        lat0, lon0, wait = route[i]
        if t < wait:
            return (lat0, lon0)
        t -= wait
        lat1, lon1 = route[i + 1][0], route[i + 1][1]
        seg_m = _dist_m((lat0, lon0), (lat1, lon1))
        travel_s = seg_m / speed_mps if speed_mps > 0 else float("inf")
        if t < travel_s:
            f = t / travel_s if travel_s > 0 else 1.0
            return (lat0 + (lat1 - lat0) * f, lon0 + (lon1 - lon0) * f)
        t -= travel_s
    return (route[-1][0], route[-1][1])


def predict_velocity(route_idx: int, elapsed_s: float,
                     speed_mps: float, horizon_s: float = 2.0) -> tuple[float, float]:
    """当前路段的先验速度 (ve, vn)：未来 horizon_s 的平均速度。
    WaitTime 停驶或已到 End 时为 0；用于 CvFilter 初值消除斜坡滞后。"""
    a = predict_position(route_idx, elapsed_s, speed_mps)
    b = predict_position(route_idx, elapsed_s + horizon_s, speed_mps)
    mean_lat = math.radians((a[0] + b[0]) / 2)
    vn = (b[0] - a[0]) * _DEG_M / horizon_s
    ve = (b[1] - a[1]) * _DEG_M * math.cos(mean_lat) / horizon_s
    return (ve, vn)
